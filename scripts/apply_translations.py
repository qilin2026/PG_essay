def apply_translations():
    """Apply title translations to all essay JSON files."""
    updated = 0
    for filepath in sorted(ESSAYS_DIR.glob("*.json")):
        with open(filepath, encoding="utf-8") as f:
            data = json.load(f)

        slug = data["slug"]
        changed = False

        # Apply title translation
        if slug in TITLE_TRANSLATIONS and not data.get("title_zh"):
            data["title_zh"] = TITLE_TRANSLATIONS[slug]
            changed = True

        if changed:
            with open(filepath, "w", encoding="utf-8") as f:
                json.dump(data, f, ensure_ascii=False, indent=2)
            updated += 1

    print(f"Updated {updated} essay files with title translations")


if __name__ == "__main__":
    apply_translations()
